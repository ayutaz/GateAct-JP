_COMPOSE = {(a, b): c for a, b, c in KANA_COMPOSE}
_ASCII_SPACE = frozenset((0x20, 0x09, 0x0A, 0x0B, 0x0C, 0x0D))


def _map_cp(cp: int) -> int:
    if 0xFF01 <= cp <= 0xFF5E:
        cp -= 0xFEE0
    elif cp == 0x3000:
        cp = 0x20
    elif 0xFF61 <= cp <= 0xFF9F:
        cp = HALFWIDTH_KANA_MAP[cp - 0xFF61]
    if 0x41 <= cp <= 0x5A:
        cp += 0x20
    return cp


def normalize_codepoints(cps: list[int]) -> list[int]:
    """コードポイント列に GateAct-norm-v1 を適用する。"""
    out: list[int] = []
    for cp in map(_map_cp, cps):
        if out and (out[-1], cp) in _COMPOSE:
            out[-1] = _COMPOSE[(out[-1], cp)]
            continue
        if cp in _ASCII_SPACE:
            if out and out[-1] != 0x20:
                out.append(0x20)
            continue
        out.append(cp)
    if out and out[-1] == 0x20:
        out.pop()
    return out


def normalize_text(text: str) -> str:
    """文字列に GateAct-norm-v1 を適用する。"""
    return "".join(map(chr, normalize_codepoints([ord(c) for c in text])))
